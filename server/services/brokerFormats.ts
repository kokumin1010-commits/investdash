export function getBrokerFormat(id: BrokerFormatId | null | undefined): BrokerFormat {
  if (!id) return GENERIC;
  return BROKER_FORMATS.find(f => f.id === id) ?? GENERIC;
}

/**
 * OCR が返した broker 名から、既知のフォーマットを推定する。
 * 取込のたびに手動選択させずに済ませるための補助。
 */
export function guessFormatFromBrokerName(brokerName: string | null): BrokerFormatId {
  if (!brokerName) return "generic";
  const normalized = brokerName.toLowerCase();

  if (normalized.includes("moomoo")) return "moomoo_jp";
  if (normalized.includes("ispeed") || normalized.includes("楽天")) return "rakuten_ispeed";
  // IBKR は表記が多い（IBKR / Interactive Brokers / 盈透 など）
  if (
    normalized.includes("ibkr") ||
    normalized.includes("interactive broker") ||
    normalized.includes("盈透")
  ) {
    return "ibkr";
  }
  /*
   * 富途は日本版 moomoo と香港版で口座が別。
   * 香港版は繁体字表記（富途證券(香港) / 保證金綜合帳戶）で見分ける。
   */
  if (
    normalized.includes("富途證券") ||
    normalized.includes("富途证券") ||
    normalized.includes("futu hk") ||
    normalized.includes("futu securities") ||
    normalized.includes("保證金綜合") ||
    normalized.includes("保证金综合")
  ) {
    return "futu_hk";
  }
  if (normalized.includes("futu") || normalized.includes("富途")) return "futu";

  // 渣打銀行（Standard Chartered）。アプリ名は SC Mobile Trading
  if (
    normalized.includes("standard chartered") ||
    normalized.includes("sc mobile") ||
    normalized.includes("渣打") ||
    normalized.includes("scb")
  ) {
    return "sc_sg";
  }

  return "generic";
}
